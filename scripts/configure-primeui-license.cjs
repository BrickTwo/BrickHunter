// Keep the license file and generated client configuration outside Git.
const fs = require('node:fs');
const path = require('node:path');
const pointer = path.resolve('.primeui-license-path');
const source =
  process.argv[2] ||
  process.env.PRIMEUI_LICENSE_FILE ||
  (fs.existsSync(pointer) ? fs.readFileSync(pointer, 'utf8').trim() : '');
if (!source)
  throw new Error('Configure your PrimeUI license with: node scripts/configure-primeui-license.cjs <license-file>');
const file = path.resolve(source);
const license = fs.readFileSync(file, 'utf8').trim();
if (!license) throw new Error('The PrimeUI license file is empty');
fs.writeFileSync(
  path.resolve('src/app/primeui-license.local.ts'),
  '// Generated by scripts/configure-primeui-license.cjs; do not commit.\nexport const primeUILicense = ' +
    JSON.stringify(license) +
    ';\n'
);
fs.writeFileSync(pointer, file + '\n');
console.log('PrimeUI license configuration generated; license value omitted.');
